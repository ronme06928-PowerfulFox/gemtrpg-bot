import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const driver = execFileSync('python', ['-c',
  "from pathlib import Path; import playwright; print(Path(playwright.__file__).parent / 'driver' / 'package')",
], {encoding:'utf8'}).trim();
const {chromium} = createRequire(import.meta.url)(driver);
const output = new URL('../../_local/hollow_data_proto/', import.meta.url);
const browser = await chromium.launch({channel:'chrome'});
const page = await browser.newPage({viewport:{width:1280, height:860}});
const errors = [];
const images = new Map();
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (/^https?:/.test(request.url())) errors.push(request.url()); });
const button = name => page.getByRole('button', {name, exact:true});
const tab = name => page.locator(`#menu-portal [data-action="tab"][data-value="${name}"]`);
const frame = name => page.locator(`[data-encounters="${name}"]`);
const visible = selector => page.locator(selector).waitFor({state:'visible'});
const fit = () => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
const shot = async name => {
  await page.evaluate(() => window.scrollTo(0, 0));
  assert(await fit(), `Horizontal overflow: ${name}`);
  images.set(name, await page.screenshot({animations:'disabled'}));
};

try {
  await page.goto(new URL('index.html', output).href);
  await visible('.main-menu');
  assert.equal(await page.locator('.menu-data button').count(), 3);
  assert.equal(await page.locator('#contrast-details tr').count(), 14);
  assert.equal(await page.locator('.contrast-panel .fail').count(), 0);
  const contrast = await page.locator('#contrast-summary').textContent();
  await shot('1280-menu.png');
  await button('マスターデータ').click();
  await visible('[data-screen="master"]');
  await button('← メインメニュー').click();
  await button('ホロウデータ').click();
  await visible('[data-screen="hollow-data"]');
  assert.match(await page.locator('.hollow-heading').evaluate(node => getComputedStyle(node).backgroundImage),
    /data:image\/webp;base64,/);
  assert.equal(await page.locator('.hollow-tab-group').count(), 3);
  assert.equal(await page.locator('.hollow-tab-group button').count(), 12);
  assert.equal(await page.locator('#unit-records button').count(), 3);
  assert.equal(await page.locator('.grade-tools [data-grade]').count(), 5);
  await shot('1280-units-a.png');
  await page.locator('[data-action="grade"][data-value="silver"]').click();
  assert.equal(await page.locator('#unit-records button').count(), 1);
  await page.locator('#unit-records button').click();
  await button('編集').click();
  await page.locator('[data-field="name"]').fill('銀脈の番人・改');
  await button('B 紫').click();
  assert.equal(await page.locator('[data-field="name"]').inputValue(), '銀脈の番人・改');
  await page.locator('[data-field="name"]').fill('銀脈の番人');
  await page.locator('[data-action="grade"][data-value=""]').click();
  assert(await button('保存').evaluate(node => {
    const button = node.getBoundingClientRect();
    const dock = document.querySelector('.prototype-dock').getBoundingClientRect();
    return button.bottom <= dock.top;
  }));
  await shot('1280-editor-b.png');
  await button('ステータス').click();
  await page.locator('[data-field="hp"]').fill('92');
  await button('保存').click();
  assert.match(await page.locator('.preview-facts').textContent(), /92/);
  await tab('stage').click();
  assert.equal(await page.locator('.cat-empty').textContent(), '項目なし');
  await tab('relic').click();
  assert.equal(await page.locator('.cat-history li').count(), 2);
  await tab('tier').click();
  await visible('[data-encounters="normal"]');
  const weight = frame('normal').getByRole('spinbutton', {name:'重み'}).first();
  await weight.fill('30');
  assert.equal(await frame('normal').locator('[data-share]').first().textContent(), '50%');
  await frame('normal').getByRole('combobox').first().selectOption('F-022');
  assert.match(await frame('normal').locator('[data-row-grades]').first().textContent(), /銀級/);
  await button('通常戦闘の行を追加').click();
  assert.equal(await frame('normal').locator('tbody tr').count(), 3);
  await frame('normal').getByRole('button', {name:'外す'}).last().click();
  await button('保存').click();
  await tab('unit').click();
  await tab('tier').click();
  assert.equal(await weight.inputValue(), '30');
  await weight.fill('70');
  await frame('normal').getByRole('combobox').first().selectOption('F-021');
  await button('保存').click();
  await shot('1280-tier-b.png');
  await button('夜色と金と比較').click();
  await visible('.comparison [data-theme="night"]');
  const roomColor = () => page.locator('.comparison [data-theme="night"]').evaluate(node => getComputedStyle(node).backgroundColor);
  const night = await roomColor();
  await shot('1280-compare-b.png');
  await button('A 青緑').click();
  assert.equal(await roomColor(), night);
  assert.equal(await page.locator('.comparison [data-theme="abyss"] h2').textContent(), '淵の夜 A');
  await shot('1280-compare-a.png');
  await button('← 戻る').click();
  await visible('[data-encounters="normal"]');
  await page.setViewportSize({width:680, height:950});
  assert.equal(await page.locator('.tier-table-wrap').evaluateAll(nodes => nodes.every(node => node.scrollWidth <= node.clientWidth)), true);
  await shot('680-tier-a.png');
  await page.setViewportSize({width:1280, height:860});
  await button('← メインメニュー').click();
  await button('ユニット管理').click();
  await visible('[data-screen="units"]');
  assert.equal(await page.locator('#unit-records button').count(), 1);
  await page.getByText('その他', {exact:true}).click();
  await shot('1280-session.png');
  await button('ホロウへ複製').click();
  assert.match(await page.getByRole('status').textContent(), /複製済み/);
  await button('複製先を開く').click();
  await visible('[data-screen="hollow-data"]');
  assert.equal(await page.locator('.unit-detail-header h3').textContent(), '街道の番兵');
  assert.equal(await page.locator('#unit-records button').count(), 4);
  assert.deepEqual(errors, []);
  for (const [name, image] of images) await writeFile(new URL(name, output), image);
  console.log(contrast);
  console.log(`Saved ${images.size} images in _local/hollow_data_proto/`);
} finally {
  await browser.close();
}
